/**
 * Generates the token CSS that is computed rather than written by hand:
 *   css/color.css     baseline scheme (light + dark through light-dark()) from the M3 seed
 *   css/motion.css    spring easings as linear() + durations, both motion schemes
 *   css/tailwind.css  optional Tailwind v4 theme mapping onto the tokens
 * `--check` fails when a committed file is stale (CI).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { colorRoles, colorVar, schemeVars } from '../src/color.ts'
import { emphasizedEasing, springEasing, springs, type MotionKind, type MotionSpeed } from '../src/motion.ts'

const BASELINE_SEED = '#6750a4'
const out = (name: string) => fileURLToPath(new URL(`../css/${name}`, import.meta.url))
const check = process.argv.includes('--check')
const HEADER = '/* Generated by packages/tokens/scripts/gen.ts. Do not edit; run `npm run gen`. */\n'
let stale = false

function emit(name: string, css: string) {
  const path = out(name)
  const text = HEADER + css
  if (check) {
    let old = ''
    try { old = readFileSync(path, 'utf8') } catch { /* missing counts as stale */ }
    if (old !== text) { console.error(`stale: css/${name}`); stale = true }
    return
  }
  writeFileSync(path, text)
}

// ---- color ---------------------------------------------------------------------------------
const light = schemeVars(BASELINE_SEED, { dark: false })
const dark = schemeVars(BASELINE_SEED, { dark: true })
const colorLines = colorRoles.map((r) => {
  const v = colorVar(r)
  return `    ${v}: light-dark(${light[v]}, ${dark[v]});`
})
emit('color.css', `/*
 * Baseline M3 scheme (seed ${BASELINE_SEED}, tonal spot, 2025 spec). Each role follows the used
 * color-scheme through light-dark(): set \`color-scheme: light | dark\` on any element to pin a mode.
 * Apps theme from their own seed with schemeVars() (TS) or by overriding these properties.
 * Zero specificity, layered: any app rule wins.
 */
@layer m3e.tokens {
  :where(:root) {
    color-scheme: light dark;
${colorLines.join('\n')}
  }
}
`)

// ---- motion --------------------------------------------------------------------------------
const kinds: MotionKind[] = ['spatial', 'effects']
const speeds: MotionSpeed[] = ['fast', 'default', 'slow']
function springBlock(scheme: 'expressive' | 'standard', indent: string): string {
  const lines: string[] = []
  for (const kind of kinds) {
    for (const speed of speeds) {
      const s = springs[scheme][kind][speed]
      const { easing, duration } = springEasing(s)
      const name = `--md-sys-motion-spring-${speed}-${kind}`
      lines.push(`${indent}/* stiffness ${s.stiffness}, damping ratio ${s.damping} */`)
      lines.push(`${indent}${name}: ${easing};`)
      lines.push(`${indent}${name}-duration: ${duration}ms;`)
    }
  }
  return lines.join('\n')
}
const durations = [
  ['short1', 50], ['short2', 100], ['short3', 150], ['short4', 200],
  ['medium1', 250], ['medium2', 300], ['medium3', 350], ['medium4', 400],
  ['long1', 450], ['long2', 500], ['long3', 550], ['long4', 600],
  ['extra-long1', 700], ['extra-long2', 800], ['extra-long3', 900], ['extra-long4', 1000],
] as const
emit('motion.css', `/*
 * M3 motion. Springs (M3 Expressive) are sampled into linear() easings; each comes with the
 * duration at which the spring settles (|x - 1| < 0.001), so always pair the two:
 *   transition: translate var(--md-sys-motion-spring-fast-spatial-duration) var(--md-sys-motion-spring-fast-spatial);
 * Spatial springs may overshoot: use them for position, size, shape and scale, never for opacity or
 * color — those take the effects springs, which are critically damped.
 * \`data-motion-scheme="standard"\` on any element switches its subtree to the calmer standard scheme.
 */
@layer m3e.tokens {
  :where(:root),
  :where([data-motion-scheme='expressive']) {
${springBlock('expressive', '    ')}
  }
  :where([data-motion-scheme='standard']) {
${springBlock('standard', '    ')}
  }
  :where(:root) {
    /* M3 easing set (pre-Expressive), still right for enter/exit pairs that must not overshoot. */
    --md-sys-motion-easing-emphasized: ${emphasizedEasing};
    --md-sys-motion-easing-emphasized-decelerate: cubic-bezier(0.05, 0.7, 0.1, 1);
    --md-sys-motion-easing-emphasized-accelerate: cubic-bezier(0.3, 0, 0.8, 0.15);
    --md-sys-motion-easing-standard: cubic-bezier(0.2, 0, 0, 1);
    --md-sys-motion-easing-standard-decelerate: cubic-bezier(0, 0, 0, 1);
    --md-sys-motion-easing-standard-accelerate: cubic-bezier(0.3, 0, 1, 1);
    --md-sys-motion-easing-legacy: cubic-bezier(0.4, 0, 0.2, 1);
    --md-sys-motion-easing-linear: linear;
${durations.map(([n, ms]) => `    --md-sys-motion-duration-${n}: ${ms}ms;`).join('\n')}
  }
}
`)

// ---- tailwind ------------------------------------------------------------------------------
const twColors = colorRoles.map((r) => {
  const v = colorVar(r)
  return `  --color-${v.replace('--md-sys-color-', '')}: var(${v});`
})
emit('tailwind.css', `/*
 * Optional Tailwind v4 mapping: \`@import '@tomato1337/m3e-tokens/tailwind.css';\` after \`@import 'tailwindcss';\`
 * gives bg-primary, text-on-surface-variant, rounded-m3-lg, shadow-level2, ease-spring-fast-spatial…
 * \`inline\` keeps the utilities pointing at the live tokens, so runtime theming still applies.
 */
@theme inline {
${twColors.join('\n')}
  --radius-m3-xs: var(--md-sys-shape-corner-extra-small);
  --radius-m3-sm: var(--md-sys-shape-corner-small);
  --radius-m3-md: var(--md-sys-shape-corner-medium);
  --radius-m3-lg: var(--md-sys-shape-corner-large);
  --radius-m3-lg-plus: var(--md-sys-shape-corner-large-increased);
  --radius-m3-xl: var(--md-sys-shape-corner-extra-large);
  --radius-m3-xl-plus: var(--md-sys-shape-corner-extra-large-increased);
  --radius-m3-2xl: var(--md-sys-shape-corner-extra-extra-large);
  --shadow-level1: var(--md-sys-elevation-level1);
  --shadow-level2: var(--md-sys-elevation-level2);
  --shadow-level3: var(--md-sys-elevation-level3);
  --shadow-level4: var(--md-sys-elevation-level4);
  --shadow-level5: var(--md-sys-elevation-level5);
${kinds.flatMap((k) => speeds.map((s) => `  --ease-spring-${s}-${k}: var(--md-sys-motion-spring-${s}-${k});`)).join('\n')}
  --ease-emphasized: var(--md-sys-motion-easing-emphasized);
  --ease-emphasized-decelerate: var(--md-sys-motion-easing-emphasized-decelerate);
  --ease-emphasized-accelerate: var(--md-sys-motion-easing-emphasized-accelerate);
}
`)

if (stale) process.exit(1)
